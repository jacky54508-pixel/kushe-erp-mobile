def data_svg(text):
  return "data:image/svg+xml,"+quote(text,safe="")

def safe_route(route):
  url=route.request.url
  if url.split("?")[0].endswith("/enterprise/index.html"):
    return route.fulfill(status=200,content_type="text/html",
                         body="<!doctype html><title>synthetic only</title>")
  if route.request.resource_type=="image":
    return route.fulfill(status=200,content_type="image/svg+xml",body=neutral_svg)
  if url.startswith(BASE) or url.startswith("data:"):
    return route.continue_()
  return route.abort()

def pdf_inspect(payload):
  doc=fitz.open(stream=payload,filetype="pdf")
  pages=len(doc)
  dims=[[round(page.rect.width,2),round(page.rect.height,2)] for page in doc]
  content="\n".join(page.get_text(sort=True) for page in doc)
  text=re.sub(r"\s+","",content)
  spans=[]
  for i,page in enumerate(doc):
    for block in page.get_text("dict")["blocks"]:
      for line in block.get("lines",[]):
        for span in line.get("spans",[]):
          if not span["text"].strip():continue
          x0,y0,x1,y1=span["bbox"]
          spans.append({"page":i,"text":span["text"],"size":round(span["size"],2),
                        "on_page":x0>=-.6 and y0>=-.6 and
                            x1<=page.rect.width+.6 and y1<=page.rect.height+.6})
  pic=doc[0].get_pixmap(matrix=fitz.Matrix(1.1,1.1),alpha=False)
  preview=Image.frombytes("RGB",(pic.width,pic.height),pic.samples)
  doc.close()
  return {"pages":pages,"dims":dims,"content":content,"text":text,
          "spans":spans,"preview":preview}

def render_side_by_side(label,base,experiment,base_pages,exp_pages):
  w=max(base.width,experiment.width)
  h=max(base.height,experiment.height)
  canvas=Image.new("RGB",(2*w+28,h+44),"#e5e7eb")
  canvas.paste(base,(0,39))
  canvas.paste(experiment,(w+28,39))
  draw=ImageDraw.Draw(canvas)
  draw.text((8,12),f"OFFICIAL CSS / {base_pages} page(s)",fill="#111")
  draw.text((w+36,12),f"SPACING ONLY / {exp_pages} page(s)",fill="#111")
  canvas.save(OUT/(label+"-first-page-comparison.png"))

